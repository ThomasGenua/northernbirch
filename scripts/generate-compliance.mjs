// Writes docs/COMPLIANCE.md: every factual claim the site makes, where it came
// from and when it was last checked, in one file a compliance officer can audit
// in one pass. It is generated from the same files the pages render from --
// content/facts.json, content/partners.json, src/data/rates.json and the claims
// rules -- so it cannot describe a site that no longer exists.
//
//   node scripts/generate-compliance.mjs          write docs/COMPLIANCE.md
//   node scripts/generate-compliance.mjs --check  fail if it is out of date (the build runs this)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RULES } from './claims-rules.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const json = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));
const facts = json('content/facts.json');
const partners = json('content/partners.json');
const rates = json('src/data/rates.json');
const OUT = 'docs/COMPLIANCE.md';

const cell = (v) => (v === null || v === undefined || v === '' ? '—' : String(v)).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (head, rows) => [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
const src = (r) => (r.sourceUrl ? `[source](${r.sourceUrl})` : 'no URL yet');
const when = (r) => (r.verified ? `${r.verified} (${r.verifiedBy})` : `**not checked** — ${r.verifiedBy || 'no source'}`);

const open = [];
const note = (what, why) => open.push(`- ${what}: ${why}`);

// --- organisation ---
for (const o of facts.organisation) {
  if (!o.verified) note(o.claim, o.verifiedBy);
  else if (!o.sourceUrl) note(o.claim, 'confirmed in the content review; no source URL yet');
}
// --- phones ---
const phoneById = Object.fromEntries(facts.phones.map((p) => [p.id, p]));
for (const p of facts.phones) {
  if (!p.verified) note(`${p.label} ${p.number}`, `check against ${p.sourceUrl}`);
  else if (!p.sourceUrl) note(`${p.label} ${p.number}`, 'confirmed in the content review; no source URL yet');
}
for (const b of facts.branches) if (!b.verified) note(`${b.name} branch address and hours`, b.verifiedBy);
if (facts._open) note('Contact data', facts._open);
// --- rates ---
const verifiedRates = Object.fromEntries(Object.entries(rates.verified).filter(([k]) => !k.startsWith('_')));
const unverifiedRates = Object.keys(rates.rates).filter((k) => !verifiedRates[k]);
if (unverifiedRates.length) note(`Posted rates ${unverifiedRates.join(', ')}`, rates.verified._everything_else);
// --- partners ---
for (const p of partners.partners) {
  if (p.status === 'live' && !p.sourceUrl) note(`${p.carrier} (${p.line})`, 'live, but no source URL yet');
  const tbc = Object.entries(p).filter(([, v]) => typeof v === 'string' && /^TO (CONFIRM|CHOOSE)/.test(v)).map(([k]) => k);
  if (tbc.length) note(`${p.line}`, `${tbc.join(', ')} still TO CONFIRM`);
}
// --- limits ---
const L = facts.limits;
if (!L.verified) note(`${L.taxYear} registered-plan limits`, `check against ${L.sourceUrl}`);

const md = `# Compliance map

<!-- Generated by scripts/generate-compliance.mjs from content/facts.json, content/partners.json,
     src/data/rates.json and scripts/claims-rules.mjs. Do not edit by hand: change the source file
     and run \`node scripts/generate-compliance.mjs\`. The build fails if this file is out of date. -->

Every factual claim this demo makes about Northern Birch Credit Union, where it came from, and when it was last checked. Anything not checked is listed under [Open items](#open-items) — **${open.length} today**.

## What this site is

- An illustrative proposal prepared by Oodler Inc. It is not a live Northern Birch Credit Union service. Every page carries a banner and a footer saying so.
- Behind a password, and \`noindex, nofollow\` on every page. See \`docs/password-protection.md\`.
- Insurance is **referral only**. The site does not quote, advise on, sell or bind insurance. The words it uses are "connect you with" and "refer you to".
- Forms collect nothing: submissions are discarded (\`netlify/functions/demo-intake.mjs\`). The advisor chat's retention is in \`docs/DATA-RETENTION.md\`.

## Organisation

${table(['Claim', 'Value', 'Source', 'Checked'], facts.organisation.map((o) => [o.claim, o.value, src(o), when(o)]))}

## Phone numbers

The build refuses any phone number not in this table, and any \`tel:\` link that dials a different number than it shows (\`scripts/check-facts.mjs\`).

${table(['Number', 'Who', 'Source', 'Checked'], facts.phones.map((p) => [p.number, p.label, src(p), when(p)]))}

## Branches

${table(['Branch', 'Address', 'Hours', 'Phone', 'Checked'], facts.branches.map((b) => [b.name, b.address, b.hours, b.phone ? phoneById[b.phone].number : 'TO CONFIRM', when(b)]))}

## Posted rates

Effective ${rates.effective}. Source: ${rates.source}. ${rates.guarantee}. Rates render from \`src/data/rates.json\`; the build refuses a rate written anywhere else (\`scripts/check-rates.mjs\`).

${table(['Rate', 'Value', 'Checked'], Object.entries(rates.rates).map(([k, v]) => [k, v, verifiedRates[k] || '**not checked**']))}

## Insurance: who underwrites what

Live arrangements exist today. Proposed ones are Oodler's pitch, and Northern Birch has agreed to none of them. The build refuses a proposed carrier's name outside the proposal pages (\`scripts/check-partners.mjs\`).

${table(['Line', 'Carrier', 'Status', 'Licence', 'Source', 'Checked'], partners.partners.map((p) => [p.line, p.carrier, p.status, p.licence, src(p), when(p)]))}

## Government limits (${L.taxYear})

${table(['Limit', 'Value'], [
  ['TFSA annual', `$${L.tfsaAnnual.toLocaleString('en-CA')}`],
  ['TFSA cumulative room since 2009', `$${L.tfsaCumulative.toLocaleString('en-CA')}`],
  ['RRSP dollar maximum', `$${L.rrspMax.toLocaleString('en-CA')}`],
  ['FHSA annual / lifetime', `$${L.fhsaAnnual.toLocaleString('en-CA')} / $${L.fhsaLifetime.toLocaleString('en-CA')}`],
  ['CESG', `${L.cesgRate} of the first $${L.cesgMatchedContribution.toLocaleString('en-CA')} a year`],
])}

Source: ${src(L)}. Checked: ${when(L)}.

## Claims the build refuses

These were corrected once, after the content review. \`scripts/check-claims.mjs\` stops any of them from coming back:

${[...new Set(RULES.map((r) => r.why))].map((w) => `- ${w.charAt(0).toUpperCase()}${w.slice(1)}`).join('\n')}

## Open items

${open.join('\n')}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(join(ROOT, OUT)) ? readFileSync(join(ROOT, OUT), 'utf8') : '';
  if (current !== md) {
    console.error(`compliance: ${OUT} is out of date with the files it is generated from. Run: node scripts/generate-compliance.mjs`);
    process.exit(1);
  }
  console.log(`compliance ok -- ${OUT} is current; ${open.length} open items`);
} else {
  writeFileSync(join(ROOT, OUT), md);
  console.log(`compliance: wrote ${OUT} (${open.length} open items)`);
}
